export default function SidebarNav() {
  const pathname = usePathname()

  const closeDrawer = () => {
    const cb = document.getElementById("sidebar-drawer") as HTMLInputElement
    if (cb) cb.checked = false
  }

  return (
    <nav className="flex-1 overflow-y-auto" style={{ padding: "12px 8px" }}>
      <div className="side-nav-label" style={{ marginBottom: 4 }}>
        Menu
      </div>
      <div style={{ display: "flex", flexDirection: "column", gap: 1 }}>
        {navItems.map((item) => {
          const isActive =
            item.href === "/dashboard"
              ? pathname === "/dashboard"
              : pathname === item.href || pathname.startsWith(item.href + "/")

          return (
            <Link
              key={item.href}
              href={item.href}
              className={`side-nav-link${isActive ? " is-active" : ""}`}
              aria-current={isActive ? "page" : undefined}
              onClick={closeDrawer}
            >
              <span
                style={{
                  flexShrink: 0,
                  color: isActive ? "var(--color-primary-hover)" : "var(--color-text-muted)",
                  transition: "color 0.15s",
                }}
              >
                {item.icon}
              </span>
              {item.label}
            </Link>
          )
        })}
      </div>
    </nav>
  )
}
